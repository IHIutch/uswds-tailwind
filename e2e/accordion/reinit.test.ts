import { expect, it } from 'vitest'
import { userEvent } from 'vitest/browser'
import { Accordion, accordionInit } from '../../packages/compat/src/accordion.js'
import { createDisposableAccordion } from './_utils.js'

const rootId = 'test'

const TEMPLATE = `
  <ul data-scope="accordion" data-part="root" id="${rootId}">
    <li data-part="item" data-value="a" data-state="open">
      <button data-part="item-trigger">Section A</button>
      <div data-part="item-content"></div>
    </li>
    <li data-part="item" data-value="b" data-state="closed">
      <button data-part="item-trigger">Section B</button>
      <div data-part="item-content"></div>
    </li>
  </ul>
`

// https://github.com/uswds/uswds/blob/v3.14.0/packages/usa-accordion/src/index.js#L84-L89 (init reads each button's current state)
it('init after destroy keeps the item the user opened', { tags: ['parity'] }, async () => {
  await using component = createDisposableAccordion(rootId, TEMPLATE)
  const { getRootEl } = component.elements
  const root = getRootEl()!
  // Looked up once: the trigger ids are regenerated by the second init.
  const [triggerA, triggerB] = root.querySelectorAll<HTMLElement>('[data-part="item-trigger"]')
  await userEvent.click(triggerB)
  expect(triggerB.getAttribute('aria-expanded')).toBe('true')

  Accordion.getInstance(root)?.destroy()
  const instances = accordionInit()

  try {
    expect(triggerA.getAttribute('aria-expanded')).toBe('false')
    expect(triggerB.getAttribute('aria-expanded')).toBe('true')
  }
  finally {
    instances.forEach(instance => instance.destroy())
  }
})
